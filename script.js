    function createCard(title, text, icon) {
      const article = document.createElement("article");
      article.className = "small-card reveal";
      article.innerHTML = `
        <span class="badge" aria-hidden="true">${icon}</span>
        <h3>${title}</h3>
        <p>${text}</p>
      `;
      return article;
    }

    function createDualPointCard(title, items) {
      const article = document.createElement("article");
      article.className = "small-card reveal";
      article.innerHTML = `
        <span class="badge" aria-hidden="true">✓</span>
        <h3>${title}</h3>
        <ul>${items.map((item) => `<li>${item}</li>`).join("")}</ul>
      `;
      return article;
    }

